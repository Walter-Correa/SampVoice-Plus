std::span<const LanguageInfo> Localization::languages() noexcept {
    return kLanguages;
}

Language Localization::parseCode(std::string_view code) noexcept {
    std::string lower;
    lower.reserve(code.size());
    for (char ch : code) {
        lower.push_back(static_cast<char>(std::tolower(static_cast<unsigned char>(ch))));
    }
    for (const auto& info : kLanguages) {
        if (lower == info.code) {
            return info.id;
        }
    }
    return Language::En;
}

const char* Localization::codeOf(Language lang) noexcept {
    const auto idx = static_cast<std::size_t>(lang);
    return (idx < kLanguageCount) ? kLanguages[idx].code : "en";
}

const char* Localization::nativeNameOf(Language lang) noexcept {
    const auto idx = static_cast<std::size_t>(lang);
    return (idx < kLanguageCount) ? kLanguages[idx].nativeName : "English";
}

const char* Localization::get(Language lang, TextKey key) noexcept {
    auto langIdx = static_cast<std::size_t>(lang);
    if (langIdx >= kLanguageCount) {
        langIdx = static_cast<std::size_t>(Language::En);
    }
    const auto keyIdx = static_cast<std::size_t>(key);
    if (keyIdx >= kKeyCount) {
        return "";
    }
    const char* text = kTranslations[langIdx][keyIdx];
    return (text != nullptr && text[0] != '\0')
               ? text
               : kTranslations[static_cast<std::size_t>(Language::En)][keyIdx];
}

