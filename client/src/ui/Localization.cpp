constexpr bool allTranslationsNonEmpty() noexcept {
    for (std::size_t lang = 0; lang < Localization::kLanguageCount; ++lang) {
        for (std::size_t key = 0; key < Localization::kKeyCount; ++key) {
            const char* s = kTranslations[lang][key];
            if (s == nullptr || s[0] == '\0') {
                return false;
            }
        }
    }
    return true;
}

static_assert(
    allTranslationsNonEmpty(),
    "Every translation entry in kTranslations across all 15 languages must be non-null and non-empty");

constexpr bool speakerHeaderMatchesOption() noexcept {
    constexpr std::size_t optIdx = static_cast<std::size_t>(TextKey::ShowSpeakerListHeader);
    constexpr std::size_t hdrIdx = static_cast<std::size_t>(TextKey::SpeakerListHeader);
    for (std::size_t lang = 0; lang < Localization::kLanguageCount; ++lang) {
        const std::string_view opt = kTranslations[lang][optIdx];
        const std::string_view hdr = kTranslations[lang][hdrIdx];
        const std::size_t firstQuote = opt.find('"');
        const std::size_t secondQuote = (firstQuote != std::string_view::npos)
            ? opt.find('"', firstQuote + 1u)
            : std::string_view::npos;
        if (firstQuote == std::string_view::npos || secondQuote == std::string_view::npos) {
            return false;
        }
        if (opt.substr(firstQuote + 1u, secondQuote - firstQuote - 1u) != hdr) {
            return false;
        }
    }
    return true;
}

static_assert(
    speakerHeaderMatchesOption(),
    "SpeakerListHeader must match the quoted label inside ShowSpeakerListHeader in all 15 languages");

